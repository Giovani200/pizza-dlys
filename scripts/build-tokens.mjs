/**
 * Generates app/tokens.css from design/tokens.json, the single source of design values.
 *
 * Mobile/desktop pairs become fluid clamp() values: exact at the 390 px and 1440 px
 * reference widths, interpolated in between. Bounds are in rem so browser zoom still
 * scales text (WCAG 1.4.4).
 */
import { readFileSync, writeFileSync } from "node:fs";

const tokens = JSON.parse(readFileSync(new URL("../design/tokens.json", import.meta.url), "utf8"));
const outputPath = new URL("../app/tokens.css", import.meta.url);

const ROOT_FONT_SIZE_PX = 16;
const { mobile_width: mobileWidth, desktop_width: desktopWidth } = tokens.layout_px;

const toKebabCase = (name) => name.replaceAll("_", "-");
const round = (value) => Number(value.toFixed(4));
const toRem = (px) => `${round(px / ROOT_FONT_SIZE_PX)}rem`;

function fluid({ mobile, desktop }) {
  const slope = (desktop - mobile) / (desktopWidth - mobileWidth);
  const interceptPx = mobile - slope * mobileWidth;
  return `clamp(${toRem(mobile)}, ${toRem(interceptPx)} + ${round(slope * 100)}vw, ${toRem(desktop)})`;
}

const declarations = [];
const declare = (name, value) => declarations.push(`  --${toKebabCase(name)}: ${value};`);

for (const [name, hex] of Object.entries(tokens.color)) declare(`color-${name}`, hex);

for (const [name, { color, opacity }] of Object.entries(tokens.alpha)) {
  declare(`alpha-${name}`, `color-mix(in srgb, var(--color-${toKebabCase(color)}) ${opacity * 100}%, transparent)`);
}

for (const [name, weight] of Object.entries(tokens.font_weight)) declare(`font-weight-${name}`, weight);
for (const [name, sizes] of Object.entries(tokens.type_scale_px)) declare(`font-size-${name}`, fluid(sizes));
for (const [name, value] of Object.entries(tokens.line_height)) declare(`line-height-${name}`, value);
for (const [name, value] of Object.entries(tokens.letter_spacing_em)) declare(`letter-spacing-${name}`, `${value}em`);
for (const value of tokens.space_px) declare(`space-${value}`, `${value}px`);
for (const [name, value] of Object.entries(tokens.radius_px)) declare(`radius-${name}`, `${value}px`);

for (const [name, value] of Object.entries(tokens.border_px)) declare(`border-width-${name}`, `${value}px`);
declare("border", "var(--border-width-default) solid var(--color-ink)");
declare("border-separator", "var(--border-width-separator) dashed");

for (const [name, offset] of Object.entries(tokens.shadow_offset_px)) {
  declare(`shadow-offset-${name}`, `${offset}px`);
  declare(`shadow-${name}`, `var(--shadow-offset-${toKebabCase(name)}) var(--shadow-offset-${toKebabCase(name)}) 0 var(--color-ink)`);
}

for (const [name, value] of Object.entries(tokens.control_height_px)) declare(`height-${name}`, `${value}px`);
for (const [name, sizes] of Object.entries(tokens.fluid_px)) declare(name, fluid(sizes));
for (const [name, value] of Object.entries(tokens.duration_s)) declare(`duration-${name}`, `${value}s`);
for (const [name, value] of Object.entries(tokens.tilt_deg)) declare(`tilt-${name}`, `${value}deg`);

const { color: halftoneColor, dot_px: dotPx, fade_px: fadePx, grid_px: gridPx } = tokens.halftone;
declare("halftone-image", `radial-gradient(var(--alpha-${toKebabCase(halftoneColor)}) ${dotPx}px, transparent ${fadePx}px)`);
declare("halftone-size", `${gridPx}px ${gridPx}px`);

const css = `/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit. */\n:root {\n${declarations.join("\n")}\n}\n`;
writeFileSync(outputPath, css);
console.log(`tokens.css: ${declarations.length} variables`);
